"""Generate common/buildings/00_boi_ownership_overrides.txt.

Private investment reaches a building group only through the ownership buildings'
investment_scores (VIC3_MODDING_LESSONS.md, "Building groups carry the economic
behaviour"). BOI's housing groups are in none of vanilla's lists, so private
capital never built housing. This copies vanilla's building_manor_house and
building_financial_district whole (first-read-wins shadow, hence 00_) and adds one
score per housing tier group. Re-run after every game patch:

    python tools/Build-OwnershipOverrides.py [game_path]

Scores agreed 2026-11-08: capitalists favour working- and middle-class housing,
aristocrats the luxury tiers. Municipal Estates and the Temporary Shelter are
government-only, so neither owner scores them.
"""
import os
import re
import sys

GAME = sys.argv[1] if len(sys.argv) > 1 else r'C:\Program Files (x86)\Steam\steamapps\common\Victoria 3\game'
MOD = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SOURCE = os.path.join(GAME, 'common', 'buildings', '11_private_infrastructure.txt')
OUT = os.path.join(MOD, 'common', 'buildings', '00_boi_ownership_overrides.txt')

WORKING = ['bg_boi_slum_housing', 'bg_boi_tenement_housing', 'bg_boi_regulated_terrace_housing',
           'bg_boi_tenement_block_housing', 'bg_boi_model_dwelling_housing', 'bg_boi_apartment_housing',
           'bg_boi_elevator_apartment_housing', 'bg_boi_streetcar_suburb_housing']
LUXURY = ['bg_boi_luxury_apartment_housing', 'bg_boi_boulevard_apartment_housing',
          'bg_boi_elevator_residence_housing', 'bg_boi_suburban_housing',
          'bg_boi_railway_suburb_housing', 'bg_boi_motor_suburb_housing']
SCORES = {
    'building_financial_district': {**{g: 1 for g in WORKING}, **{g: 0.5 for g in LUXURY}},
    'building_manor_house': {**{g: 0.25 for g in WORKING}, **{g: 0.5 for g in LUXURY}},
}


def block(text, key):
    m = re.search(r'(?m)^' + re.escape(key) + r'\s*=\s*\{', text)
    if not m:
        raise SystemExit(f'{key} not found in {SOURCE}')
    depth = 0
    for j in range(text.index('{', m.start()), len(text)):
        if text[j] == '{':
            depth += 1
        elif text[j] == '}':
            depth -= 1
            if depth == 0:
                return text[m.start():j + 1]
    raise SystemExit(f'unbalanced {key}')


def add_scores(body, scores):
    m = re.search(r'\n\tinvestment_scores\s*=\s*\{', body)
    if not m:
        raise SystemExit('investment_scores not found')
    depth = 0
    for j in range(body.index('{', m.start()), len(body)):
        if body[j] == '{':
            depth += 1
        elif body[j] == '}':
            depth -= 1
            if depth == 0:
                break
    lines = ['\t\t# BOI: housing tiers (2026-11-08)']
    for group, score in scores.items():
        lines.append(f'\t\t{group}_score = {{ # BOI\n\t\t\tgroup = "{group}"\n\t\t\tscore = {{ value = {score} }}\n\t\t}}')
    return body[:j] + '\n'.join(lines) + '\n\t' + body[j:]


text = open(SOURCE, encoding='utf-8-sig').read().replace('\r\n', '\n')
parts = ['# Generated by tools/Build-OwnershipOverrides.py from vanilla '
         'common/buildings/11_private_infrastructure.txt; do not edit by hand.\n'
         '# Full copies of two vanilla buildings (first-read-wins shadow). The only BOI\n'
         '# change is the block of housing scores marked "# BOI" in each investment_scores.\n'
         '# Patch debt: listed in README.md, "Vanilla overrides and mod conflicts".']
for key, scores in SCORES.items():
    parts.append(add_scores(block(text, key), scores))
with open(OUT, 'w', encoding='utf-8-sig', newline='\n') as f:
    f.write('\n\n'.join(parts) + '\n')
print(f'Wrote {OUT}')
