r"""Write horse_seed_reductions.tsv from horse_seed_tiers.tsv.

    python tools/Set-HorseSeedTiers.py [--retain T1 T2 T3 T4]

Each state's levels become round(levels x its tier's retained share). Tier 0
stays at zero. Afterwards run Regenerate-WorldSeed.ps1 to rebuild the seed, and
update the expected counts in Test-Seed.ps1 and Test-HorseSeedSafety.ps1.
"""
import argparse, math, os

here = os.path.dirname(os.path.abspath(__file__))
ap = argparse.ArgumentParser()
ap.add_argument('--retain', nargs=4, type=float, default=[0.85, 0.60, 0.35, 0.25])
retain = dict(zip((1, 2, 3, 4), ap.parse_args().retain))

lines = [
    '# GENERATED by Set-HorseSeedTiers.py from horse_seed_tiers.tsv. Do not hand-edit.',
    '# 1836 Horse Ranch level overrides; zero removes the ranch.',
    '# Retained shares by historical tier: ' + ', '.join(f'tier {t} {retain[t]:.0%}' for t in retain),
]
totals = {t: [0, 0, 0] for t in (0, 1, 2, 3, 4)}
for line in open(os.path.join(here, 'horse_seed_tiers.tsv'), encoding='utf-8'):
    if not line.startswith('STATE_'):
        continue
    state, tier, levels = line.split()
    tier, levels = int(tier), int(levels)
    new = 0 if tier == 0 else math.floor(levels * retain[tier] + 0.5)
    lines.append(f'{state}\t{new}')
    totals[tier][0] += levels
    totals[tier][1] += new
    totals[tier][2] += 1 if new else 0
open(os.path.join(here, 'horse_seed_reductions.tsv'), 'w', encoding='utf-8', newline='\n').write('\n'.join(sorted(lines, key=lambda l: (l[0] != '#', ))) + '\n')
for t, (old, new, n) in totals.items():
    if t:
        print(f'tier {t}: {old} -> {new} levels in {n} states')
print(f'total: {sum(v[0] for v in totals.values())} -> {sum(v[1] for v in totals.values())} levels, {sum(v[2] for v in totals.values())} ranches')
