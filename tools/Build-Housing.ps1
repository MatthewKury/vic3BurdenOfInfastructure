function Test-HousingGroup {
    param([string]$Group, [string[]]$Roots)
    $visited = @{}
    while ($Group) {
        if ($Group -in $Roots) { return $true }
        if ($visited.ContainsKey($Group)) { throw "Building group cycle: $Group" }
        $visited[$Group] = $true
        if (-not $groups.ContainsKey($Group)) { return $false }
        $Group = [regex]::Match($groups[$Group], '(?m)^\s*parent_group\s*=\s*(\w+)').Groups[1].Value
    }
    return $false
}
