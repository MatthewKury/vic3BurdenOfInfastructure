    foreach ($file in (Get-SourceFiles (Join-Path $root 'common/modifier_type_definitions'))) {
        foreach ($block in (Get-HousingScriptBlocks ([IO.File]::ReadAllText($file.FullName)))) { $knownModifiers[$block.Key] = $true }
    }
