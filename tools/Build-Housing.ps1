# 1836 residential seed. Demand per state comes from a measured headless run
# (tools/housing_seed_demand_1836.tsv; see tools/REGENERATE.md). History-created
# buildings start staffed. Apartment Blocks need a later tech, and shelters are an
# emergency measure, so neither is seeded.
# Above 1 on purpose: rounding small states down to no building loses about a fifth.
$seedCoverageBasic = 0.92; $seedCoverageLuxury = 1.1
$outputSlum = 6.0; $outputTenement = 7.0; $outputLuxuryBasic = 2.5; $outputLuxury = 6.0
# Crowded districts of the 1830s beyond what the rule below finds: Naples, St
# Petersburg, Bombay, Cairo, Constantinople, Canton, Boston and Amsterdam.
$slumCities = @('STATE_CAMPANIA', 'STATE_INGRIA', 'STATE_BOMBAY', 'STATE_LOWER_EGYPT', 'STATE_EASTERN_THRACE', 'STATE_WESTERN_GUANGDONG', 'STATE_MASSACHUSETTS', 'STATE_HOLLAND')
# Seeded housing is privately owned (2026-11-08; it was all country-owned, so
# every 1836 slum showed as government property). Vanilla's history gives
# private buildings to an ownership building in the state: a manor house for
# aristocrats, a financial district for capitalists. It never creates either
# one by hand. Here, rented housing in a state with industry (4+ levels) is
# split between capitalists (speculative builders, the larger half) and
# aristocrats (ground landlords). Elsewhere, and for the villa belts and
# gentry estates seeded as suburbs, it goes to aristocrats. Municipal Estates
# and shelters stay government buildings, and neither is seeded.
$seedCapitalistIndustry = 4
function New-SeedBuilding([string]$Building, [string]$Owner, [string]$Region, [int]$Levels, [int]$CapitalistLevels, [string[]]$Methods) {
    $methodList = ($Methods | ForEach-Object { '"' + $_ + '"' }) -join ' '
    $owners = [Collections.Generic.List[string]]::new()
    foreach ($share in @(@('building_financial_district', $CapitalistLevels), @('building_manor_house', ($Levels - $CapitalistLevels)))) {
        if ($share[1] -le 0) { continue }
        $owners.Add(@"
					building = {
						type = "$($share[0])"
						country = "c:$Owner"
						levels = $($share[1])
						region = "$Region"
					}
"@)
    }
@"
			create_building = {
				building = "$Building"
				add_ownership = {
$($owners -join "`n")
				}
				reserves = 1
				activate_production_methods = { $methodList }
			}
"@
}
$seedRegions = [ordered]@{}
foreach ($row in (Import-Csv -LiteralPath (Join-Path $PSScriptRoot 'housing_seed_demand_1836.tsv') -Delimiter "`t")) {
    $culture = [Globalization.CultureInfo]::InvariantCulture
    $stateDemand = [double]::Parse($row.housing_demand, $culture)
    $luxuryDemand = [double]::Parse($row.luxury_demand, $culture)
    $urban = [int]$row.urban_center
    $industry = [int]$row.industry
    # Luxury first: dense cities get apartments, and the largest also villa belts.
    # Elsewhere it is gentry estates and country seats.
    $luxuryLevels = [int][Math]::Floor($seedCoverageLuxury * $luxuryDemand / $outputLuxury + 0.5)
    $apartments = 0
    $suburbs = 0
    if ($urban -ge 10) { $apartments = [int][Math]::Ceiling($luxuryLevels / 2); $suburbs = $luxuryLevels - $apartments }
    elseif ($urban -ge 4) { $apartments = $luxuryLevels }
    else { $suburbs = $luxuryLevels }
    # Basic housing is net of what subsistence and luxury buildings already supply.
    $existing = if ([int]$row.residential -eq 0) { [double]::Parse($row.housing_supply, $culture) } else { 0.0 }
    $basicTarget = ($seedCoverageBasic * $stateDemand) - $existing - ($outputLuxuryBasic * $luxuryLevels)
    # Slums only in crowded industrial cities and great ports: each state with one
    # takes the flat mortality penalty, so spreading them widely would be punishing.
    $slums = 0
    $tenements = 0
    if ($basicTarget -gt 0) {
        $crowded = (($urban -ge 7 -and $industry -ge 8) -or $row.region -in $slumCities) -and $stateDemand -ge 15
        if ($crowded) { $slums = [int][Math]::Max(1, [Math]::Floor(0.4 * $basicTarget / $outputSlum)) }
        $tenements = [int][Math]::Max(0, [Math]::Floor(($basicTarget - ($slums * $outputSlum)) / $outputTenement + 0.5))
    }
    $created = [Collections.Generic.List[string]]::new()
    $industrial = $industry -ge $seedCapitalistIndustry
    $capShare = { param([int]$n) if ($industrial) { [int][Math]::Ceiling($n / 2) } else { 0 } }
    $aptCap = if ($industrial) { $apartments } else { 0 }
    if ($slums -gt 0) { $created.Add((New-SeedBuilding 'building_boi_slums' $row.owner $row.region $slums (& $capShare $slums) @('pm_boi_slums'))) }
    if ($tenements -gt 0) { $created.Add((New-SeedBuilding 'building_boi_tenements' $row.owner $row.region $tenements (& $capShare $tenements) @('pm_boi_tenements'))) }
    if ($apartments -gt 0) { $created.Add((New-SeedBuilding 'building_boi_luxury_apartments' $row.owner $row.region $apartments $aptCap @('pm_boi_luxury_apartments'))) }
    if ($suburbs -gt 0) { $created.Add((New-SeedBuilding 'building_boi_suburbs' $row.owner $row.region $suburbs 0 @('pm_boi_suburbs'))) }
    if ($created.Count -eq 0) { continue }
    if (-not $seedRegions.Contains($row.region)) { $seedRegions[$row.region] = [Collections.Generic.List[string]]::new() }
    $seedRegions[$row.region].Add("`t`tregion_state:$($row.owner) = {`n$($created -join "`n")`n`t`t}")
}
$seedBlocks = foreach ($region in $seedRegions.Keys) { "`ts:$region = {`n$($seedRegions[$region] -join "`n")`n`t}" }
Write-HousingScript (Join-Path $OutputPath 'common/history/buildings/zz_boi_housing_seed_generated.txt') ("# Generated by tools/Build-Housing.ps1 from tools/housing_seed_demand_1836.tsv; do not edit.`nBUILDINGS = {`n" + ($seedBlocks -join "`n") + "`n}")
# Residential roster, from tools/Housing-Tiers.ps1.
function Format-HousingNumber([double]$Value) {
    return ([Math]::Round($Value, 3)).ToString('0.###', [Globalization.CultureInfo]::InvariantCulture)
}
function Format-HousingModifiers($Table) {
    return (($Table.Keys | ForEach-Object { "$_ = $(Format-HousingNumber $Table[$_])" }) -join "`n   ")
}
