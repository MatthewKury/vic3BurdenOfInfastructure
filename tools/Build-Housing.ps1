foreach ($key in ($buildings.Keys | Sort-Object)) {
    $source = $buildings[$key]
    $group = [regex]::Match($source, '(?m)^\s*building_group\s*=\s*(\w+)').Groups[1].Value
    # 1.15: the Cossack Host (bg_cossack_host, under bg_ranching) is a subsistence-style
    # settlement (5,000 farmers and labourers per level, subsistence-style output), so it houses itself.
    if (Test-HousingGroup $group @('bg_subsistence_agriculture', 'bg_subsistence_ranching', 'bg_cossack_host')) {
        $pmg = 'pmg_boi_subsistence_housing'
        $subsistenceTypes.Add($key)
    }
    elseif (Test-HousingGroup $group $ruralRoots) {
        $pmg = 'pmg_boi_company_housing'
        $companyTypes.Add($key)
    }
    else { continue }
    if ($modBuildings.ContainsKey($key)) {
        $code = [regex]::Replace($source, '(?m)#[^\r\n]*', '')
        if ($code -notmatch "production_method_groups\s*=\s*\{[^}]*\b$pmg\b") { throw "$key is defined by the mod, so it must list $pmg itself; the generator will not shadow it." }
        continue
    }
    if (-not $vanillaBuildings.ContainsKey($key)) { throw "Unexpected building source: $key" }
    # [^\r\n]* keeps a trailing comment on the opening line (1.15 copper mine).
    $pattern = '(production_method_groups\s*=\s*\{[^\r\n]*)'
    if ([regex]::Matches($source, $pattern).Count -ne 1) { throw "Expected exactly one PM group list: $key" }
    $shadows.Add([regex]::Replace($source, $pattern, ('$1' + "`n`t`t$pmg")))
}
