    foreach ($direction in @('input','output')) {
        foreach ($operation in @('add','mult')) { $modifierKeys.Add("goods_${direction}_${good}_${operation}") }
    }
}
foreach ($profession in @('laborers','farmers','machinists','engineers','clerks','shopkeepers','clergymen','aristocrats','capitalists','slaves')) {
    $modifierKeys.Add("building_${profession}_mortality_mult")
}
$modifierDefinitions = foreach ($key in ($modifierKeys | Sort-Object -Unique)) {
    if ($knownModifiers.ContainsKey($key)) { continue }
    $color = if ($key -match '^goods_output_') { 'good' } else { 'bad' }
    $percent = if ($key.EndsWith('_mult')) { 'percent = yes' } else { '' }
    "$key = {`n decimals = 1`n color = $color`n $percent`n game_data = { ai_value = 0 }`n}"
}
