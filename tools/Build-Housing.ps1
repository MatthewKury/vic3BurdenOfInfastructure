# Country scope. Each employer housing law permits No Housing plus one tier.
# Move ONLY buildings on another paying tier to the permitted one, per state;
# No Housing must survive enactment untouched. The state limit keeps the monthly
# pass cheap, since it runs for every country.
function New-HousingEnforcement([string[]]$From, [string]$To) {
    $conditions = ($From | ForEach-Object { "has_active_production_method = $_" }) -join "`n                        "
    $switches = foreach ($key in $companyTypes) {
@"
        if = {
            limit = {
                any_scope_building = {
                    is_building_type = $key
                    OR = {
                        $conditions
                    }
                }
            }
            activate_production_method = {
                building_type = $key
                production_method = $To
            }
        }
"@
    }
@"
    every_scope_state = {
        limit = {
            any_scope_building = {
                OR = {
                        $conditions
                }
            }
        }
$($switches -join "`n")
    }
"@
}
