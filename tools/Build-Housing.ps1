[CmdletBinding()]
param(
    [string]$GamePath = 'C:\Program Files (x86)\Steam\steamapps\common\Victoria 3\game',
    [string]$ModPath,
    [string]$OutputPath
)
$ErrorActionPreference = 'Stop'
if (-not $ModPath) { $ModPath = Split-Path $PSScriptRoot -Parent }
if (-not $OutputPath) { $OutputPath = $ModPath }
. (Join-Path $PSScriptRoot 'Housing-ScriptTools.ps1')

# The five files this script owns. They are never read back as input: the
# output folder is the mod itself, and re-reading them would add the housing
# PM group twice and treat its own modifier declarations as already known.
$generatedNames = @('00_boi_housing_rural_generated.txt', '00_buy_packages.txt',
    'zz_boi_housing_fallback_generated.txt', 'zz_boi_housing_generated.txt', 'zz_boi_housing_seed_generated.txt')
function Get-SourceFiles([string]$Directory) {
    if (-not (Test-Path -LiteralPath $Directory)) { return @() }
    Get-ChildItem -LiteralPath $Directory -Filter '*.txt' | Where-Object Name -notin $generatedNames | Sort-Object Name
}

# Generate keyed shadows from the installed game. BOI's own building blocks
# are read too, but only to find rural types it defines (the Horse Ranch) or
# already shadows: those must list the housing PM group by hand, because a
# generated copy would sort first (00_) and replace BOI's definition.
$buildings = @{}
$vanillaBuildings = @{}
$modBuildings = @{}
foreach ($file in (Get-SourceFiles (Join-Path $GamePath 'common/buildings'))) {
    foreach ($block in (Get-HousingScriptBlocks ([IO.File]::ReadAllText($file.FullName)))) {
        $buildings[$block.Key] = $block.Text
        $vanillaBuildings[$block.Key] = $true
    }
}
foreach ($file in (Get-SourceFiles (Join-Path $ModPath 'common/buildings'))) {
    foreach ($block in (Get-HousingScriptBlocks ([IO.File]::ReadAllText($file.FullName)))) {
        $buildings[$block.Key] = $block.Text
        $modBuildings[$block.Key] = $true
    }
}
$groups = @{}
foreach ($root in @($GamePath, $ModPath)) {
    foreach ($file in (Get-SourceFiles (Join-Path $root 'common/building_groups'))) {
        foreach ($block in (Get-HousingScriptBlocks ([IO.File]::ReadAllText($file.FullName)))) { $groups[$block.Key] = $block.Text }
    }
}
function Test-HousingGroup {
    param([string]$Group, [string[]]$Roots)
    $visited = @{}
    while ($Group) {
        if ($Group -in $Roots) { return $true }
        if ($visited.ContainsKey($Group)) { throw "Building group cycle: $Group" }
        $visited[$Group] = $true
        if (-not $groups.ContainsKey($Group)) { return $false }
        $Group = [regex]::Match($groups[$Group], '(?m)^\s*parent_group\s*=\s*(\w+)').Groups[1].Value
    }
    return $false
}
$ruralRoots = @('bg_agriculture', 'bg_ranching', 'bg_plantations', 'bg_mining', 'bg_logging', 'bg_fishing', 'bg_whaling', 'bg_rubber', 'bg_oil_extraction')
$shadows = [Collections.Generic.List[string]]::new()
$companyTypes = [Collections.Generic.List[string]]::new()
$subsistenceTypes = [Collections.Generic.List[string]]::new()
foreach ($key in ($buildings.Keys | Sort-Object)) {
    $source = $buildings[$key]
    $group = [regex]::Match($source, '(?m)^\s*building_group\s*=\s*(\w+)').Groups[1].Value
    if (Test-HousingGroup $group @('bg_subsistence_agriculture', 'bg_subsistence_ranching')) {
        $pmg = 'pmg_boi_subsistence_housing'
        $subsistenceTypes.Add($key)
    }
    elseif (Test-HousingGroup $group $ruralRoots) {
        $pmg = 'pmg_boi_company_housing'
        $companyTypes.Add($key)
    }
    else { continue }
    if ($modBuildings.ContainsKey($key)) {
        $code = [regex]::Replace($source, '(?m)#[^\r\n]*', '')
        if ($code -notmatch "production_method_groups\s*=\s*\{[^}]*\b$pmg\b") { throw "$key is defined by the mod, so it must list $pmg itself; the generator will not shadow it." }
        continue
    }
    if (-not $vanillaBuildings.ContainsKey($key)) { throw "Unexpected building source: $key" }
    $pattern = '(production_method_groups\s*=\s*\{)'
    if ([regex]::Matches($source, $pattern).Count -ne 1) { throw "Expected exactly one PM group list: $key" }
    $shadows.Add([regex]::Replace($source, $pattern, ('$1' + "`n`t`t$pmg")))
}
if ($companyTypes.Count -lt 20 -or $subsistenceTypes.Count -ne 5) { throw "Unexpected coverage: $($companyTypes.Count) rural / $($subsistenceTypes.Count) subsistence. Review game update." }
# Match BOI's early 00_boi_* keyed-building override convention.
Write-HousingScript (Join-Path $OutputPath 'common/buildings/00_boi_housing_rural_generated.txt') ("# Generated by tools/Build-Housing.ps1 from vanilla; do not edit. BOI's own rural buildings list the housing PM group by hand.`n" + ($shadows -join "`n`n"))

# Preserve all vanilla non-housing needs and political strength. Added expenditure
# is deliberate; household budgets are still being calibrated.
# Housing's cost as a share of a level's core game basket, with housing at base
# price: none when Destitute (1-4), rising to 5% at the 1.75x price ceiling by the
# top of Struggling (9), then an S-curve to 15% at Lavish (50), and flat above it.
function Get-HousingDemandShare([int]$Wealth) {
    $strugglingTop = (5.0 / 1.75) / 100
    $plateau = 0.15
    if ($Wealth -le 4) { return 0.0 }
    if ($Wealth -le 9) { return $strugglingTop * ($Wealth - 4) / 5 }
    if ($Wealth -ge 50) { return $plateau }
    $x = ($Wealth - 9) / 41
    return $strugglingTop + ($plateau - $strugglingTop) * (3 * $x * $x - 2 * $x * $x * $x)
}
$packages = Get-HousingScriptBlocks ([IO.File]::ReadAllText((Join-Path $GamePath 'common/buy_packages/00_buy_packages.txt')))
$demand = [Collections.Generic.List[string]]::new()
foreach ($package in $packages) {
    if ($package.Key -notmatch '^wealth_(\d+)$') { throw "Unexpected buy package: $($package.Key)" }
    $wealth = [int]$Matches[1]
    $core = 0.0
    foreach ($need in [regex]::Matches($package.Text, '(?m)^\s*popneed_\w+\s*=\s*([0-9.]+)')) {
        $core += [double]::Parse($need.Groups[1].Value, [Globalization.CultureInfo]::InvariantCulture)
    }
    $share = Get-HousingDemandShare $wealth
    # Round down through Struggling, so its cap holds exactly.
    $total = if ($wealth -le 9) { [Math]::Floor($share * $core) } else { [Math]::Round($share * $core) }
    $basic = [Math]::Min(10 + (2 * $wealth), $total)
    $luxury = $total - $basic
    $addition = ''
    if ($basic -gt 0) { $addition += "`n`t`tpopneed_boi_housing = $basic" }
    if ($luxury -gt 0) { $addition += "`n`t`tpopneed_boi_luxury_housing = $luxury" }
    $pattern = '(goods\s*=\s*\{)(?:[^\S\r\n]*#[^\r\n]*)?'
    if ([regex]::Matches($package.Text, $pattern).Count -ne 1) { throw "Unexpected goods block: $($package.Key)" }
    $demand.Add([regex]::Replace($package.Text, $pattern, ('$1' + $addition)))
}
if ($demand.Count -ne 99) { throw 'Expected 99 wealth packages. Review game update.' }
# Replace the complete vanilla file: all 99 keys are preserved and extended.
# Do not rely on duplicate-key ordering for buy packages.
Write-HousingScript (Join-Path $OutputPath 'common/buy_packages/00_buy_packages.txt') ("# Generated by tools/Build-Housing.ps1. Housing demand is a share of each level's core game basket; see Get-HousingDemandShare.`n" + ($demand -join "`n`n"))

# Country scope. Each employer housing law permits No Housing plus one tier.
# Move ONLY buildings on another paying tier to the permitted one, per state;
# No Housing must survive enactment untouched. The state limit keeps the monthly
# pass cheap, since it runs for every country.
function New-HousingEnforcement([string[]]$From, [string]$To) {
    $conditions = ($From | ForEach-Object { "has_active_production_method = $_" }) -join "`n                        "
    $switches = foreach ($key in $companyTypes) {
@"
        if = {
            limit = {
                any_scope_building = {
                    is_building_type = $key
                    OR = {
                        $conditions
                    }
                }
            }
            activate_production_method = {
                building_type = $key
                production_method = $To
            }
        }
"@
    }
@"
    every_scope_state = {
        limit = {
            any_scope_building = {
                OR = {
                        $conditions
                }
            }
        }
$($switches -join "`n")
    }
"@
}
$enforceCamps = New-HousingEnforcement @('pm_boi_work_town', 'pm_boi_serviced_town') 'pm_boi_work_camp'
$enforceTowns = New-HousingEnforcement @('pm_boi_work_camp', 'pm_boi_serviced_town') 'pm_boi_work_town'
$enforceServiced = New-HousingEnforcement @('pm_boi_work_camp', 'pm_boi_work_town') 'pm_boi_serviced_town'
$closeHousing = New-HousingEnforcement @('pm_boi_work_camp', 'pm_boi_work_town') 'pm_boi_no_company_housing'
Write-HousingScript (Join-Path $OutputPath 'common/scripted_effects/zz_boi_housing_fallback_generated.txt') ("# Generated. Country scope; runtime fallback ordering requires verification.`nboi_housing_enforce_work_camps_effect = {`n$enforceCamps`n}`n`nboi_housing_enforce_work_towns_effect = {`n$enforceTowns`n}`n`n# Serviced Town needs modern_sewerage; without it paying tiers go to No Housing.`nboi_housing_enforce_serviced_towns_effect = {`n    if = {`n        limit = { has_technology_researched = modern_sewerage }`n$enforceServiced`n    }`n    else = {`n$closeHousing`n    }`n}")
# 1836 residential seed. Demand per state comes from a measured headless run
# (tools/housing_seed_demand_1836.tsv; see tools/REGENERATE.md). History-created
# buildings start staffed. Apartment Blocks need a later tech, and shelters are an
# emergency measure, so neither is seeded.
# Above 1 on purpose: rounding small states down to no building loses about a fifth.
$seedCoverageBasic = 1.0; $seedCoverageLuxury = 1.1
$outputSlum = 6.0; $outputTenement = 7.0; $outputLuxuryBasic = 2.5; $outputLuxury = 6.0
# Crowded districts of the 1830s beyond what the rule below finds: Naples, St
# Petersburg, Bombay, Cairo, Constantinople, Canton, Boston and Amsterdam.
$slumCities = @('STATE_CAMPANIA', 'STATE_INGRIA', 'STATE_BOMBAY', 'STATE_LOWER_EGYPT', 'STATE_EASTERN_THRACE', 'STATE_WESTERN_GUANGDONG', 'STATE_MASSACHUSETTS', 'STATE_HOLLAND')
function New-SeedBuilding([string]$Building, [string]$Owner, [int]$Levels, [string[]]$Methods) {
    $methodList = ($Methods | ForEach-Object { '"' + $_ + '"' }) -join ' '
@"
			create_building = {
				building = "$Building"
				add_ownership = {
					country = {
						country = "c:$Owner"
						levels = $Levels
					}
				}
				reserves = 1
				activate_production_methods = { $methodList }
			}
"@
}
$seedRegions = [ordered]@{}
foreach ($row in (Import-Csv -LiteralPath (Join-Path $PSScriptRoot 'housing_seed_demand_1836.tsv') -Delimiter "`t")) {
    $culture = [Globalization.CultureInfo]::InvariantCulture
    $stateDemand = [double]::Parse($row.housing_demand, $culture)
    $luxuryDemand = [double]::Parse($row.luxury_demand, $culture)
    $urban = [int]$row.urban_center
    $industry = [int]$row.industry
    # Luxury first: dense cities get apartments, and the largest also villa belts.
    # Elsewhere it is gentry estates and country seats.
    $luxuryLevels = [int][Math]::Floor($seedCoverageLuxury * $luxuryDemand / $outputLuxury + 0.5)
    $apartments = 0
    $suburbs = 0
    if ($urban -ge 10) { $apartments = [int][Math]::Ceiling($luxuryLevels / 2); $suburbs = $luxuryLevels - $apartments }
    elseif ($urban -ge 4) { $apartments = $luxuryLevels }
    else { $suburbs = $luxuryLevels }
    # Basic housing is net of what subsistence and luxury buildings already supply.
    $existing = if ([int]$row.residential -eq 0) { [double]::Parse($row.housing_supply, $culture) } else { 0.0 }
    $basicTarget = ($seedCoverageBasic * $stateDemand) - $existing - ($outputLuxuryBasic * $luxuryLevels)
    # Slums only in crowded industrial cities and great ports: each state with one
    # takes the flat SoL penalty, so spreading them widely would be punishing.
    $slums = 0
    $tenements = 0
    if ($basicTarget -gt 0) {
        $crowded = (($urban -ge 7 -and $industry -ge 8) -or $row.region -in $slumCities) -and $stateDemand -ge 15
        if ($crowded) { $slums = [int][Math]::Max(1, [Math]::Floor(0.4 * $basicTarget / $outputSlum)) }
        $tenements = [int][Math]::Max(0, [Math]::Floor(($basicTarget - ($slums * $outputSlum)) / $outputTenement + 0.5))
    }
    $created = [Collections.Generic.List[string]]::new()
    if ($slums -gt 0) { $created.Add((New-SeedBuilding 'building_boi_slums' $row.owner $slums @('pm_boi_slums'))) }
    if ($tenements -gt 0) { $created.Add((New-SeedBuilding 'building_boi_tenements' $row.owner $tenements @('pm_boi_tenements'))) }
    if ($apartments -gt 0) { $created.Add((New-SeedBuilding 'building_boi_luxury_apartments' $row.owner $apartments @('pm_boi_luxury_apartments'))) }
    if ($suburbs -gt 0) { $created.Add((New-SeedBuilding 'building_boi_suburbs' $row.owner $suburbs @('pm_boi_suburbs', 'pm_boi_horse_commuting'))) }
    if ($created.Count -eq 0) { continue }
    if (-not $seedRegions.Contains($row.region)) { $seedRegions[$row.region] = [Collections.Generic.List[string]]::new() }
    $seedRegions[$row.region].Add("`t`tregion_state:$($row.owner) = {`n$($created -join "`n")`n`t`t}")
}
$seedBlocks = foreach ($region in $seedRegions.Keys) { "`ts:$region = {`n$($seedRegions[$region] -join "`n")`n`t}" }
Write-HousingScript (Join-Path $OutputPath 'common/history/buildings/zz_boi_housing_seed_generated.txt') ("# Generated by tools/Build-Housing.ps1 from tools/housing_seed_demand_1836.tsv; do not edit.`nBUILDINGS = {`n" + ($seedBlocks -join "`n") + "`n}")
# New goods and unused profession/mortality combinations need explicit dynamic
# modifier declarations. Only declare keys absent from vanilla and base BOI.
$knownModifiers = @{}
foreach ($root in @($GamePath, $ModPath)) {
    foreach ($file in (Get-SourceFiles (Join-Path $root 'common/modifier_type_definitions'))) {
        foreach ($block in (Get-HousingScriptBlocks ([IO.File]::ReadAllText($file.FullName)))) { $knownModifiers[$block.Key] = $true }
    }
}
$modifierKeys = [Collections.Generic.List[string]]::new()
$modifierKeys.Add('goods_input_furniture_add')
foreach ($good in @('boi_housing','boi_luxury_housing')) {
    foreach ($direction in @('input','output')) {
        foreach ($operation in @('add','mult')) { $modifierKeys.Add("goods_${direction}_${good}_${operation}") }
    }
}
foreach ($profession in @('laborers','farmers','machinists','engineers','clerks','shopkeepers','clergymen','aristocrats','capitalists','slaves')) {
    $modifierKeys.Add("building_${profession}_mortality_mult")
}
$modifierDefinitions = foreach ($key in ($modifierKeys | Sort-Object -Unique)) {
    if ($knownModifiers.ContainsKey($key)) { continue }
    $color = if ($key -match '^goods_output_') { 'good' } else { 'bad' }
    $percent = if ($key.EndsWith('_mult')) { 'percent = yes' } else { '' }
    "$key = {`n decimals = 1`n color = $color`n $percent`n game_data = { ai_value = 0 }`n}"
}
Write-HousingScript (Join-Path $OutputPath 'common/modifier_type_definitions/zz_boi_housing_generated.txt') ("# Generated missing dynamic types; do not duplicate vanilla declarations.`n" + ($modifierDefinitions -join "`n`n"))
Write-Host "Generated housing shadows: $($companyTypes.Count) rural buildings, $($subsistenceTypes.Count) subsistence buildings, $($demand.Count) wealth packages."
