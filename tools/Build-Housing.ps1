# The files this script owns. They are never read back as input: the output
# folder is the mod itself, and re-reading them would add the housing PM group
# twice and treat its own modifier declarations as already known.
$generatedNames = @('00_boi_housing_rural_generated.txt', '00_buy_packages.txt',
    'zz_boi_housing_fallback_generated.txt', 'zz_boi_housing_generated.txt', 'zz_boi_housing_seed_generated.txt',
    '50_boi_housing_tiers_generated.txt')
function Get-SourceFiles([string]$Directory) {
    if (-not (Test-Path -LiteralPath $Directory)) { return @() }
    Get-ChildItem -LiteralPath $Directory -Filter '*.txt' | Where-Object Name -notin $generatedNames | Sort-Object Name
}

