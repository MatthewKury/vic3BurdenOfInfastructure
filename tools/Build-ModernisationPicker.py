"""Generate City Modernisation's region picker from the Rail Network Survey's.

Both decisions choose one strategic region with the same continent-then-region
events. Rather than keep two hand-written copies of seven events and a dozen
triggers, this copies the survey's (events/boi_rail_survey_events.txt .1-.7 and
the boi_rs_has_eligible_in_* triggers) with City Modernisation's names:

    boi_rail_survey.N (N = 1-7)  -> boi_city_modernisation.N
    boi_rs_has_eligible_in_*     -> boi_cm_has_eligible_in_*
    boi_rs_state_eligible        -> boi_cm_state_eligible
    boi_rs_choose_region         -> boi_cm_choose_region

Option names (continents, regions, Back, Not now) keep the survey's loc keys.
Re-run whenever the survey's picker changes:

    python tools/Build-ModernisationPicker.py
"""
import os
import re

MOD = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
EVENTS = os.path.join(MOD, 'events', 'boi_rail_survey_events.txt')
TRIGGERS = os.path.join(MOD, 'common', 'scripted_triggers', '52_boi_rail_survey_triggers.txt')
OUT_EVENTS = os.path.join(MOD, 'events', 'boi_city_modernisation_picker_generated.txt')
OUT_TRIGGERS = os.path.join(MOD, 'common', 'scripted_triggers', '53_boi_city_modernisation_picker_generated.txt')
HEADER = '# Generated by tools/Build-ModernisationPicker.py from {src}; do not edit by hand.\n'


def read(path):
    return open(path, encoding='utf-8-sig').read().replace('\r\n', '\n')


def blocks(text, pattern):
    for m in re.finditer(r'(?m)^(' + pattern + r')\s*=\s*\{', text):
        depth = 0
        for j in range(text.index('{', m.start()), len(text)):
            if text[j] == '{':
                depth += 1
            elif text[j] == '}':
                depth -= 1
                if depth == 0:
                    yield text[m.start():j + 1]
                    break


events = read(EVENTS)
picker = '\n\n'.join(blocks(events, r'boi_rail_survey\.[1-7]'))
picker = re.sub(r'\bboi_rail_survey\.([1-7]) = \{', r'boi_city_modernisation.\1 = {', picker)
picker = re.sub(r'id = boi_rail_survey\.([1-7])\b', r'id = boi_city_modernisation.\1', picker)
picker = re.sub(r'title = boi_rail_survey\.([1-7])\.t\b', r'title = boi_city_modernisation.\1.t', picker)
picker = picker.replace('desc = boi_rail_survey.1.d', 'desc = boi_city_modernisation.1.d')
picker = picker.replace('desc = boi_rail_survey.region.d', 'desc = boi_city_modernisation.region.d')
picker = picker.replace('flavor = boi_rail_survey.1.f', 'flavor = boi_city_modernisation.1.f')
picker = picker.replace('boi_rs_has_eligible_in_', 'boi_cm_has_eligible_in_')
picker = picker.replace('boi_rs_choose_region', 'boi_cm_choose_region')
picker = picker.replace('boi_rs_picker_cancel_tt', 'boi_cm_picker_cancel_tt')
picker = re.sub(r'video = "[a-z_]+"', 'video = "europenorthamerica_london_center"', picker)
picker = picker.replace('event_map.dds', 'event_industry.dds')
leftover = re.findall(r'boi_rs_[a-z_]+|boi_rail_survey\.[0-9]+\b(?!\.)', picker)
assert not leftover, leftover

triggers = read(TRIGGERS)
copied = '\n\n'.join(blocks(triggers, r'boi_rs_has_eligible_in_[a-z_]+'))
copied = copied.replace('boi_rs_has_eligible_in_', 'boi_cm_has_eligible_in_')
copied = copied.replace('boi_rs_state_eligible', 'boi_cm_state_eligible')
assert 'boi_rs_' not in copied

with open(OUT_EVENTS, 'w', encoding='utf-8-sig', newline='\n') as f:
    f.write(HEADER.format(src='events/boi_rail_survey_events.txt') +
            '# City Modernisation region picker (.1 continent, .2-.7 regions).\n'
            'namespace = boi_city_modernisation\n\n' + picker + '\n')
with open(OUT_TRIGGERS, 'w', encoding='utf-8-sig', newline='\n') as f:
    f.write(HEADER.format(src='common/scripted_triggers/52_boi_rail_survey_triggers.txt') +
            '# Country scope: a modernisation can start on each continent / in a region.\n\n' + copied + '\n')
print(f'Wrote {OUT_EVENTS} and {OUT_TRIGGERS}')
