"""Generate BOI's copies of the vanilla map city types (gfx/map/city_data/city_types/).

A building with a city_type must be listed in every city-type file of that hub type,
or the game asserts "Failed creating backing building" (VIC3_MODDING_LESSONS.md,
"Three silent gates"). Each file is one top-level block, so the whole file is copied
from the game (base and DLC folders) and BOI's lines are added before its closing
brace. Re-run after every game patch:

    python tools/Build-CityTypes.py [game_path]

Models (agreed 2026-11-08; no new meshes, only vanilla ones):
  Horse Ranch   (farm) - whatever the file uses for building_livestock_ranch
  Road Works    (city) - whatever the file uses for building_construction_sector
  Rail Works    (city) - whatever the file uses for building_army_logistics_center
  Harbour Works (port) - the culture's lighthouse (vanilla ports have no model)

DLC files are copied too and keep their has_dlc_feature triggers, so a player
without the DLC never gets that city type. Their mesh names still load; see the
conflicts list in README.md.
"""
import os
import re
import sys

GAME = sys.argv[1] if len(sys.argv) > 1 else r'C:\Program Files (x86)\Steam\steamapps\common\Victoria 3\game'
MOD = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
REL = os.path.join('gfx', 'map', 'city_data', 'city_types')
OUT = os.path.join(MOD, REL)

# building to add -> (hub type, vanilla building whose model it copies, fallback mesh)
COPIES = {
    'farm': [('building_boi_horse_ranch', 'building_livestock_ranch', '"european_rural_ranch_01_mesh"')],
    'city': [('building_boi_infrastructure', 'building_construction_sector', '"generic_manufactory_03_mesh"'),
             ('building_boi_rail_works', 'building_army_logistics_center', '"generic_logisticscenter_01_mesh"')],
}
# Port: the lighthouse by file prefix. South Asian and Indian use the Arabic one, as
# vanilla's southasian files reuse arabic meshes; the rest of Europe uses European.
LIGHTHOUSE = {'african': 'african', 'arabic': 'arabic', 'asian': 'asian', 'latin': 'latin',
              'southasian': 'arabic', 'indian': 'arabic', 'japan': 'asian'}


def sources():
    yield os.path.join(GAME, REL)
    dlc = os.path.join(GAME, 'dlc')
    for name in sorted(os.listdir(dlc)):
        path = os.path.join(dlc, name, REL)
        if os.path.isdir(path):
            yield path


def mesh_list(text, key):
    m = re.search(r'(?m)^\s*' + re.escape(key) + r'\s*=\s*\{([^{}]*)\}', text)
    if not m:
        return None
    meshes = re.findall(r'"[^"]+"', m.group(1))
    return ' '.join(meshes) if meshes else None


def closing_brace(text):
    m = re.search(r'(?m)^[A-Za-z_][A-Za-z0-9_]*\s*=\s*\{', text)
    depth = 0
    for j in range(text.index('{', m.start()), len(text)):
        if text[j] == '{':
            depth += 1
        elif text[j] == '}':
            depth -= 1
            if depth == 0:
                return j
    raise ValueError('unbalanced')


os.makedirs(OUT, exist_ok=True)
written = 0
for folder in sources():
    for name in sorted(os.listdir(folder)):
        if not name.endswith('.txt') or name.startswith('00_'):
            continue
        text = open(os.path.join(folder, name), encoding='utf-8-sig').read().replace('\r\n', '\n')
        hub = re.search(r'(?m)^\s*city_type\s*=\s*([a-z_]+)', text)
        if not hub or hub.group(1) not in ('farm', 'city', 'port'):
            continue
        hub = hub.group(1)
        lines = ['', '\t# BOI: Burden of Infrastructure buildings, added by tools/Build-CityTypes.py']
        if hub == 'port':
            prefix = name.split('_')[0]
            lines.append(f'\tbuilding_boi_harbour_works = {{"{LIGHTHOUSE.get(prefix, "european")}_lighthouse_01_mesh"}} # BOI')
        else:
            for building, model, fallback in COPIES[hub]:
                lines.append(f'\t{building} = {{{mesh_list(text, model) or fallback}}} # BOI: as {model}')
        j = closing_brace(text)
        out = (f'# Generated by tools/Build-CityTypes.py from {os.path.relpath(os.path.join(folder, name), GAME)};\n'
               '# do not edit by hand. Vanilla content plus the lines marked BOI.\n'
               + text[:j].rstrip('\n') + '\n' + '\n'.join(lines) + '\n' + text[j:])
        with open(os.path.join(OUT, name), 'w', encoding='utf-8-sig', newline='\n') as f:
            f.write(out)
        written += 1
print(f'Wrote {written} city type files to {OUT}')
