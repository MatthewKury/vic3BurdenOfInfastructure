[CmdletBinding()]
param(
    [string]$GamePath = 'C:\Program Files (x86)\Steam\steamapps\common\Victoria 3\game',
    [string]$ModPath,
    [string]$OutputPath
)
$ErrorActionPreference = 'Stop'
if (-not $ModPath) { $ModPath = Split-Path $PSScriptRoot -Parent }
if (-not $OutputPath) { $OutputPath = Join-Path $PSScriptRoot 'housing-prototype' }
. (Join-Path $PSScriptRoot 'Housing-ScriptTools.ps1')

# Generate keyed shadows from the installed game, then overlay BOI's building
# definitions first. This preserves the custom Horse Ranch and all existing PMs.
$buildings = @{}
foreach ($directory in @((Join-Path $GamePath 'common/buildings'), (Join-Path $ModPath 'common/buildings'))) {
    foreach ($file in (Get-ChildItem -LiteralPath $directory -Filter '*.txt' | Sort-Object Name)) {
        foreach ($block in (Get-HousingScriptBlocks ([IO.File]::ReadAllText($file.FullName)))) {
            $buildings[$block.Key] = $block.Text
        }
    }
}
$groups = @{}
foreach ($file in Get-ChildItem (Join-Path $GamePath 'common/building_groups') -Filter '*.txt') {
    foreach ($block in (Get-HousingScriptBlocks ([IO.File]::ReadAllText($file.FullName)))) { $groups[$block.Key] = $block.Text }
}
function Test-HousingGroup {
    param([string]$Group, [string[]]$Roots)
    $visited = @{}
    while ($Group) {
        if ($Group -in $Roots) { return $true }
        if ($visited.ContainsKey($Group)) { throw "Building group cycle: $Group" }
        $visited[$Group] = $true
        if (-not $groups.ContainsKey($Group)) { return $false }
        $Group = [regex]::Match($groups[$Group], '(?m)^\s*parent_group\s*=\s*(\w+)').Groups[1].Value
    }
    return $false
}
$ruralRoots = @('bg_agriculture', 'bg_ranching', 'bg_plantations', 'bg_mining', 'bg_logging', 'bg_fishing', 'bg_whaling', 'bg_rubber', 'bg_oil_extraction')
$shadows = [Collections.Generic.List[string]]::new()
$companyTypes = [Collections.Generic.List[string]]::new()
$subsistenceTypes = [Collections.Generic.List[string]]::new()
foreach ($key in ($buildings.Keys | Sort-Object)) {
    $source = $buildings[$key]
    $group = [regex]::Match($source, '(?m)^\s*building_group\s*=\s*(\w+)').Groups[1].Value
    if (Test-HousingGroup $group @('bg_subsistence_agriculture', 'bg_subsistence_ranching')) {
        $pmg = 'pmg_boi_subsistence_housing'
        $subsistenceTypes.Add($key)
    }
    elseif (Test-HousingGroup $group $ruralRoots) {
        $pmg = 'pmg_boi_company_housing'
        $companyTypes.Add($key)
    }
    else { continue }
    $pattern = '(production_method_groups\s*=\s*\{)'
    if ([regex]::Matches($source, $pattern).Count -ne 1) { throw "Expected exactly one PM group list: $key" }
    $shadows.Add([regex]::Replace($source, $pattern, ('$1' + "`n`t`t$pmg")))
}
if ($companyTypes.Count -lt 20 -or $subsistenceTypes.Count -ne 5) { throw "Unexpected coverage: $($companyTypes.Count) rural / $($subsistenceTypes.Count) subsistence. Review game update." }
# Match BOI's early 00_boi_* keyed-building override convention.
Write-HousingScript (Join-Path $OutputPath 'common/buildings/00_boi_housing_rural_generated.txt') ("# Generated by tools/Build-HousingPrototype.ps1; load the prototype after BOI.`n" + ($shadows -join "`n`n"))

# Preserve all vanilla non-housing needs and political strength. Added expenditure
# is deliberate: this is an unbalanced test economy, not a world campaign seed.
$packages = Get-HousingScriptBlocks ([IO.File]::ReadAllText((Join-Path $GamePath 'common/buy_packages/00_buy_packages.txt')))
$demand = [Collections.Generic.List[string]]::new()
foreach ($package in $packages) {
    if ($package.Key -notmatch '^wealth_(\d+)$') { throw "Unexpected buy package: $($package.Key)" }
    $wealth = [int]$Matches[1]
    $basic = 10 + (2 * $wealth)
    $luxury = if ($wealth -ge 15) { ($wealth - 14) * ($wealth - 14) } else { 0 }
    $addition = "`n`t`tpopneed_boi_housing = $basic"
    if ($luxury -gt 0) { $addition += "`n`t`tpopneed_boi_luxury_housing = $luxury" }
    $pattern = '(goods\s*=\s*\{)(?:[^\S\r\n]*#[^\r\n]*)?'
    if ([regex]::Matches($package.Text, $pattern).Count -ne 1) { throw "Unexpected goods block: $($package.Key)" }
    $demand.Add([regex]::Replace($package.Text, $pattern, ('$1' + $addition)))
}
if ($demand.Count -ne 99) { throw 'Expected 99 wealth packages. Review game update.' }
# Replace the complete vanilla file: all 99 keys are preserved and extended.
# Do not rely on duplicate-key ordering for buy packages.
Write-HousingScript (Join-Path $OutputPath 'common/buy_packages/00_buy_packages.txt') ("# Generated prototype demand. Basic = 10 + 2 * wealth; luxury = (wealth - 14)^2 from wealth 15.`n" + ($demand -join "`n`n"))

# Country scope. Change ONLY types currently using the prohibited PM in each
# state. Permitted company housing must survive enactment untouched.
$fallback = [Collections.Generic.List[string]]::new()
foreach ($key in $companyTypes) {
    $fallback.Add(@"
        if = {
            limit = {
                any_scope_building = {
                    is_building_type = $key
                    has_active_production_method = pm_boi_hostile_company_housing
                }
            }
            activate_production_method = {
                building_type = $key
                production_method = pm_boi_no_company_housing
            }
        }
"@)
}
Write-HousingScript (Join-Path $OutputPath 'common/scripted_effects/zz_boi_housing_fallback_generated.txt') ("# Generated. Country scope; runtime fallback ordering requires verification.`nboi_housing_remove_hostile_effect = {`n    every_scope_state = {`n" + ($fallback -join "`n") + "`n    }`n}")
# New goods and unused profession/mortality combinations need explicit dynamic
# modifier declarations. Only declare keys absent from vanilla and base BOI.
$knownModifiers = @{}
foreach ($root in @($GamePath, $ModPath)) {
    foreach ($file in Get-ChildItem (Join-Path $root 'common/modifier_type_definitions') -Filter '*.txt') {
        foreach ($block in (Get-HousingScriptBlocks ([IO.File]::ReadAllText($file.FullName)))) { $knownModifiers[$block.Key] = $true }
    }
}
$modifierKeys = [Collections.Generic.List[string]]::new()
$modifierKeys.Add('goods_input_furniture_add')
foreach ($good in @('boi_housing','boi_luxury_housing')) {
    foreach ($direction in @('input','output')) {
        foreach ($operation in @('add','mult')) { $modifierKeys.Add("goods_${direction}_${good}_${operation}") }
    }
}
foreach ($profession in @('laborers','farmers','machinists','engineers','clerks','shopkeepers','clergymen','aristocrats','capitalists','slaves')) {
    $modifierKeys.Add("building_${profession}_mortality_mult")
}
$modifierDefinitions = foreach ($key in ($modifierKeys | Sort-Object -Unique)) {
    if ($knownModifiers.ContainsKey($key)) { continue }
    $color = if ($key -match '^goods_output_') { 'good' } else { 'bad' }
    $percent = if ($key.EndsWith('_mult')) { 'percent = yes' } else { '' }
    "$key = {`n decimals = 1`n color = $color`n $percent`n game_data = { ai_value = 0 }`n}"
}
Write-HousingScript (Join-Path $OutputPath 'common/modifier_type_definitions/zz_boi_housing_generated.txt') ("# Generated missing dynamic types; do not duplicate vanilla declarations.`n" + ($modifierDefinitions -join "`n`n"))
Write-Host "Generated housing shadows: $($companyTypes.Count) rural buildings, $($subsistenceTypes.Count) subsistence buildings, $($demand.Count) wealth packages."
