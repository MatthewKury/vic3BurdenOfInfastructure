[CmdletBinding()]
param(
    [string]$GamePath = 'C:\Program Files (x86)\Steam\steamapps\common\Victoria 3\game',
    [string]$ModPath,
    [string]$OutputPath,
    # Add the water need to the HOUSING prototype's buy packages instead of building
    # a second competing copy. Use this when both optional modules are wanted: both
    # replace common/buy_packages/00_buy_packages.txt, and whichever loads first
    # wins the whole file, so only ONE module may carry the file.
    [switch]$MergeIntoHousing
)
$ErrorActionPreference = 'Stop'
if (-not $ModPath) { $ModPath = Split-Path $PSScriptRoot -Parent }
if (-not $OutputPath) { $OutputPath = Join-Path $PSScriptRoot 'water-prototype' }
. (Join-Path $PSScriptRoot 'Housing-ScriptTools.ps1')

# Household water need at wealth W: 8 + W expenditure units. Modest and monotonic:
# like Heating (26 at wealth 10) it is a necessity, not a luxury, so it does not
# take off at high wealth. PLACEHOLDER - calibrate against supply in play.
function Get-WaterDemand([int]$wealth) { 8 + $wealth }

if ($MergeIntoHousing) {
    $path = Join-Path $PSScriptRoot 'housing-prototype/common/buy_packages/00_buy_packages.txt'
    if (-not (Test-Path -LiteralPath $path)) { throw "Housing prototype buy packages not found: $path. Run Build-HousingPrototype.ps1 first." }
    $source = [IO.File]::ReadAllText($path)
    $changed = 0
    $packages = Get-HousingScriptBlocks $source
    foreach ($package in $packages) {
        if ($package.Key -notmatch '^wealth_(\d+)$') { throw "Unexpected buy package: $($package.Key)" }
        if ($package.Text.Contains('popneed_boi_water')) { continue }
        $addition = "`n`t`tpopneed_boi_water = $(Get-WaterDemand ([int]$Matches[1]))"
        $pattern = '(goods\s*=\s*\{)'
        if ([regex]::Matches($package.Text, $pattern).Count -ne 1) { throw "Unexpected goods block: $($package.Key)" }
        $patched = [regex]::Replace($package.Text, $pattern, ('$1' + $addition))
        $source = $source.Replace($package.Text, $patched)
        $changed++
    }
    Write-HousingScript $path $source
    Write-Host "Merged water demand into $changed housing wealth packages. Enable only the housing prototype; the water prototype is not needed."
    return
}

# Keep every vanilla need and political strength; add one line per package.
$packages = Get-HousingScriptBlocks ([IO.File]::ReadAllText((Join-Path $GamePath 'common/buy_packages/00_buy_packages.txt')))
$demand = [Collections.Generic.List[string]]::new()
foreach ($package in $packages) {
    if ($package.Key -notmatch '^wealth_(\d+)$') { throw "Unexpected buy package: $($package.Key)" }
    $addition = "`n`t`tpopneed_boi_water = $(Get-WaterDemand ([int]$Matches[1]))"
    $pattern = '(goods\s*=\s*\{)'
    if ([regex]::Matches($package.Text, $pattern).Count -ne 1) { throw "Unexpected goods block: $($package.Key)" }
    $demand.Add([regex]::Replace($package.Text, $pattern, ('$1' + $addition)))
}
if ($demand.Count -ne 99) { throw 'Expected 99 wealth packages. Review game update.' }
# Replace the complete vanilla file: all 99 keys are preserved and extended. Do not
# rely on duplicate-key ordering for buy packages.
Write-HousingScript (Join-Path $OutputPath 'common/buy_packages/00_buy_packages.txt') ("# Generated by tools/Build-WaterPrototype.ps1. Household water need = 8 + wealth.`n" + ($demand -join "`n`n"))
Write-Host "Generated water demand in $($demand.Count) wealth packages."
